// ─── Main Component ──────────────────────────────────

export default function BuildDoc() {
  const [activeSection, setActiveSection] = useState<SectionId>('overview');
  const [live, setLive] = useState<LiveData | null>(null);
  const [loading, setLoading] = useState(true);

  useEffect(() => {
    fetch('/api/build-doc')
      .then(r => r.json())
      .then(data => { setLive(data); setLoading(false); })
      .catch(() => setLoading(false));
  }, []);

  const handleDownloadSection = (id: SectionId) => {
    const label = sectionList.find(s => s.id === id)?.label || id;
    const md = generateMarkdown(id, live);
    downloadMarkdown(md, `theplanticu-${id}.md`);
  };

  const handleDownloadAll = () => {
    const md = generateMarkdown('all', live);
    downloadMarkdown(md, 'theplanticu-build-document.md');
  };

  const renderSection = () => {
    switch (activeSection) {
      case 'overview': return <OverviewSection />;
      case 'architecture': return <ArchitectureSection live={live} />;
      case 'dataflow': return <DataFlowSection />;
      case 'pages': return <PagesSection />;
      case 'modules': return <ModulesSection live={live} />;
      case 'integrations': return <IntegrationsSection live={live} />;
      case 'api': return <ApiEndpointsSection live={live} />;
      case 'database': return <DatabaseSection live={live} />;
      case 'rendering': return <RenderingSection />;
      case 'config': return <ConfigSection live={live} />;
    }
  };

  return (
    <div className="space-y-6">
      {/* Header */}
      <div className="flex items-center justify-between">
        <div>
          <h2 className="text-2xl font-bold">Build Document</h2>
          <p className="text-gray-400 text-sm mt-1">
            Complete technical documentation for ThePlantICU Content Engine
            {live && <span className="text-green-400 ml-2">- Live data loaded</span>}
            {loading && <span className="text-yellow-400 ml-2">- Loading...</span>}
          </p>
        </div>
        <div className="flex gap-2">
          <DownloadButton onClick={() => handleDownloadSection(activeSection)} label="Download Section" />
          <button
            onClick={handleDownloadAll}
            className="px-4 py-2 bg-green-600 hover:bg-green-500 rounded-lg text-sm font-medium transition-colors"
          >
            Download Full Doc
          </button>
        </div>
      </div>

      {/* Section Navigation */}
      <div className="flex gap-1 overflow-x-auto pb-1">
        {sectionList.map((s) => (
          <button
            key={s.id}
            onClick={() => setActiveSection(s.id)}
            className={`px-3 py-1.5 text-xs font-medium rounded-lg transition-colors whitespace-nowrap ${
              activeSection === s.id
                ? 'bg-green-600 text-white'
                : 'bg-gray-800 text-gray-400 hover:bg-gray-700 hover:text-gray-200'
            }`}
          >
            {s.label}
          </button>
        ))}
      </div>

      {/* Active Section */}
      {renderSection()}
    </div>
  );
}
